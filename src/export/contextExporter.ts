import * as vscode from 'vscode';
import { promises as fs } from 'fs';
import * as path from 'path';
import { createHash } from 'crypto';
import { CodeGraph, GraphNode, callersOf, calleesOf } from '../models/graph';

function markdownEscape(value: string): string {
	return value.replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
}

function relativeSourceLink(file: string, line?: number, prefix = '../'): string {
	const encodedFile = file.split('/').map(encodeURIComponent).join('/');
	return `[${file}${line ? `:${line}` : ''}](${prefix}${encodedFile}${line ? `#L${line}` : ''})`;
}

export async function exportContext(folder: vscode.WorkspaceFolder, graph: CodeGraph, outputDirectory: string): Promise<void> {
	const root = folder.uri.fsPath;
	const output = path.resolve(root, outputDirectory);
	if (output !== root && !output.startsWith(root + path.sep)) {
		throw new Error('The CodeMapper output directory must be inside the workspace.');
	}
	const modulesDirectory = path.join(output, 'modules');
	await fs.mkdir(modulesDirectory, { recursive: true });
	const nodes = [...graph.nodes].sort((a, b) => a.id.localeCompare(b.id));
	const edges = [...graph.edges].sort((a, b) =>
		a.type.localeCompare(b.type) || a.source.localeCompare(b.source) || a.target.localeCompare(b.target) ||
		(a.sourceLine ?? 0) - (b.sourceLine ?? 0));
	const nodeById = new Map(nodes.map(node => [node.id, node]));
	const modules = nodes.filter(node => node.type === 'module' && node.file);
	const functions = nodes.filter(node => node.type === 'function' || node.type === 'method');
	const functionData = functions.map(node => ({
		...node,
		callers: callersOf(graph, node.id).map(edge => ({ id: edge.source, resolution: edge.resolution, sourceLine: edge.sourceLine })),
		callees: calleesOf(graph, node.id).map(edge => ({ id: edge.target, resolution: edge.resolution, sourceLine: edge.sourceLine })),
	}));
	const generatedAt = graph.metadata.indexedAt;
	const byFile = new Map<string, GraphNode[]>();
	for (const node of nodes.filter(item => item.file && ['function', 'method', 'class'].includes(item.type))) {
		const list = byFile.get(node.file!) ?? [];
		list.push(node);
		byFile.set(node.file!, list);
	}
	const moduleRows = modules.map(node => `| [${markdownEscape(node.name)}](modules/${moduleDocName(node.file ?? node.name)}) | ${node.file ?? 'unknown'} |`).join('\n');
	const keyFunctions = functions.slice(0, 30).map(node => `- **${markdownEscape(node.signature ?? node.qualifiedName)}** — ${node.file ? relativeSourceLink(node.file, node.startLine) : 'unknown source'}`).join('\n');
	const diagnostics = graph.metadata.diagnostics.length
		? graph.metadata.diagnostics.map(item => `- ${item.file}${item.line ? `:${item.line}` : ''}: ${markdownEscape(item.message)}`).join('\n')
		: 'No parser diagnostics.';
	const moduleLinks = modules.map(node => `- [${node.name}](modules/${moduleDocName(node.file ?? node.name)})`).join('\n');
	const overview = `# Codebase map: ${folder.name}

Generated by CodeMapper at ${generatedAt}.

## Repository overview

Static Python analysis found ${modules.length} modules, ${nodes.filter(node => node.type === 'class').length} classes, and ${functions.length} functions and methods. Relationships are best-effort static facts, not guaranteed runtime execution traces.

## Indexed languages

- Python

## Major modules

| Module | Source |
|---|---|
${moduleRows || '| No Python modules found | |'}

## Architecture summary

Module dependency and function-call edges were extracted from Python imports and syntax-level calls. Dynamic dispatch and runtime-generated relationships may be unknown.

## Key entry points

${edges.filter(edge => edge.type === 'ENTRYPOINT_INVOKES_FUNCTION').map(edge => `- ${nodeById.get(edge.target)?.qualifiedName ?? edge.target}`).join('\n') || '- Unknown: no conventional __main__ entry points were detected.'}

## Important functions

${keyFunctions || '- No functions found.'}

## Module navigation

${moduleLinks || '- No modules found.'}

## Diagnostics

${diagnostics}
`;
	const architecture = `# Architecture

Generated at ${generatedAt}. Structural descriptions below are inferred only from static imports and calls.

## Module dependencies

\`\`\`mermaid
${mermaid(graph, 'modules')}
\`\`\`

## Structural patterns

- Module dependency cycles: ${hasCycle(modules, edges.filter(edge => edge.type === 'MODULE_IMPORTS_MODULE')) ? 'detected' : 'not detected'}.
- Application entry points: ${edges.filter(edge => edge.type === 'ENTRYPOINT_INVOKES_FUNCTION').length}.
- Dynamic or unresolved calls: ${edges.filter(edge => edge.type === 'FUNCTION_CALLS_FUNCTION' && edge.resolution === 'unresolved').length}.
- Other architectural facts: unknown unless represented by a graph relationship.
`;
	const entrypoints = `# Entry points

Entry-point detection is best-effort static analysis. It does not assert actual runtime execution.

${edges.filter(edge => edge.type === 'ENTRYPOINT_INVOKES_FUNCTION').map(edge => {
	const target = nodeById.get(edge.target);
	return `## ${target?.qualifiedName ?? edge.target}\n\n- Source: ${target?.file ? relativeSourceLink(target.file, target.startLine) : 'unknown'}\n- Resolution: ${edge.resolution}\n- Statically reachable calls: ${(target ? reachableCalls(graph, target.id) : []).map(id => nodeById.get(id)?.qualifiedName ?? id).join(', ') || 'none found'}\n`;
}).join('\n') || 'No entry points were detected. The application entry point is unknown.'}

## Unresolved call relationships

${edges.filter(edge => edge.type === 'FUNCTION_CALLS_FUNCTION' && edge.resolution === 'unresolved').map(edge => `- ${nodeById.get(edge.source)?.qualifiedName ?? edge.source} → ${nodeById.get(edge.target)?.name ?? edge.target} (line ${edge.sourceLine ?? 'unknown'})`).join('\n') || 'None detected.'}
`;
	const files: Record<string, string> = {
		'CODEBASE.md': overview,
		'architecture.md': architecture,
		'entrypoints.md': entrypoints,
		'graph.json': JSON.stringify(graph, null, 2) + '\n',
		'functions.json': JSON.stringify(functionData, null, 2) + '\n',
		'graph.mmd': mermaid(graph, 'calls') + '\n',
	};
	for (const [name, content] of Object.entries(files)) {
		await atomicWrite(path.join(output, name), content);
	}
	const currentModuleDocs = new Set(modules.map(module => moduleDocName(module.file ?? module.qualifiedName)));
	const manifestPath = path.join(output, '.modules.json');
	try {
		const previous = JSON.parse(await fs.readFile(manifestPath, 'utf8')) as string[];
		for (const name of previous) {
			if (typeof name === 'string' && !currentModuleDocs.has(name) && path.basename(name) === name && name.endsWith('.md')) {
				await fs.rm(path.join(modulesDirectory, name), { force: true });
			}
		}
	} catch (error) {
		if ((error as NodeJS.ErrnoException).code !== 'ENOENT') {
			if (error instanceof SyntaxError) {
				throw new Error('The CodeMapper module manifest is invalid. Remove .modules.json after reviewing it, then export again.');
			}
			throw error;
		}
	}
	for (const module of modules) {
		const rel = module.file ?? module.qualifiedName;
		const owned = byFile.get(rel) ?? [];
		const outgoingImports = edges.filter(edge => edge.source === module.id && edge.type === 'MODULE_IMPORTS_MODULE');
		const incomingCalls = edges.filter(edge => edge.type === 'FUNCTION_CALLS_FUNCTION' && owned.some(node => node.id === edge.target) && nodeById.get(edge.source)?.file !== rel);
		const outgoingCalls = edges.filter(edge => edge.type === 'FUNCTION_CALLS_FUNCTION' && owned.some(node => node.id === edge.source) &&
			(nodeById.get(edge.target)?.file !== rel || edge.resolution === 'unresolved'));
		const body = `# Module ${module.qualifiedName}

Source: ${relativeSourceLink(rel, undefined, '../../')}

## Dependencies

${outgoingImports.map(edge => `- ${nodeById.get(edge.target)?.qualifiedName ?? edge.target}`).join('\n') || '- None found'}

## Defined symbols

${owned.map(node => {
		const where = node.file ? relativeSourceLink(node.file, node.startLine, '../../') : 'unknown source';
		const signature = node.signature ? `\`${markdownEscape(node.signature)}\`` : `\`${markdownEscape(node.type)} ${markdownEscape(node.qualifiedName)}\``;
		const doc = node.docstring ? `\n\n  ${markdownEscape(node.docstring)}` : '';
		return `- ${signature} — ${where}${doc}`;
	}).join('\n') || '- No functions or classes detected.'}

## Incoming calls

${incomingCalls.map(edge => `- ${nodeById.get(edge.source)?.qualifiedName ?? edge.source} → ${nodeById.get(edge.target)?.qualifiedName ?? nodeById.get(edge.target)?.name ?? edge.target} (${edge.resolution})`).join('\n') || '- None found'}

## Outgoing calls

${outgoingCalls.map(edge => `- ${nodeById.get(edge.source)?.qualifiedName ?? edge.source} → ${nodeById.get(edge.target)?.qualifiedName ?? nodeById.get(edge.target)?.name ?? edge.target} (${edge.resolution})`).join('\n') || '- None found'}
`;
		await atomicWrite(path.join(modulesDirectory, moduleDocName(rel)), body);
	}
	await atomicWrite(manifestPath, JSON.stringify([...currentModuleDocs].sort(), null, 2) + '\n');
}

export async function updateAgentsFile(folder: vscode.WorkspaceFolder, outputDirectory: string): Promise<void> {
	const file = path.join(folder.uri.fsPath, 'AGENTS.md');
	const start = '<!-- BEGIN CODEMAPPER CONTEXT -->';
	const end = '<!-- END CODEMAPPER CONTEXT -->';
	const section = `${start}
## CodeMapper repository context

Generated static context is available in \`${outputDirectory}/CODEBASE.md\`, with module maps in \`${outputDirectory}/modules/\` and the machine-readable graph in \`${outputDirectory}/graph.json\`.

Before changing a function, inspect its callers and callees in \`${outputDirectory}/functions.json\`; review module dependencies in \`${outputDirectory}/architecture.md\`. Static graphs can be incomplete for dynamic Python behavior. The actual source code remains authoritative.
${end}`;
	let original = '';
	try {
		original = await fs.readFile(file, 'utf8');
	} catch (error) {
		if ((error as NodeJS.ErrnoException).code !== 'ENOENT') {
			throw error;
		}
	}
	const startAt = original.indexOf(start);
	const endAt = original.indexOf(end);
	let updated: string;
	if (startAt >= 0 && endAt > startAt) {
		updated = original.slice(0, startAt) + section + original.slice(endAt + end.length);
	} else if (startAt >= 0 || endAt >= 0) {
		throw new Error('AGENTS.md contains an incomplete CodeMapper marker pair; edit it manually before updating.');
	} else {
		updated = original ? original.trimEnd() + '\n\n' + section + '\n' : section + '\n';
	}
	await atomicWrite(file, updated);
}

function moduleDocName(file: string): string {
	const safe = file.replace(/[^a-zA-Z0-9._-]+/g, '_');
	return `${safe}-${createHash('sha256').update(file).digest('hex').slice(0, 8)}.md`;
}

function mermaid(graph: CodeGraph, mode: 'modules' | 'calls'): string {
	const allowed = mode === 'modules' ? ['MODULE_IMPORTS_MODULE'] : ['FUNCTION_CALLS_FUNCTION'];
	const nodes = graph.nodes.filter(node => mode === 'modules' ? node.type === 'module' : ['function', 'method'].includes(node.type));
	const edges = graph.edges.filter(edge => allowed.includes(edge.type) && nodes.some(node => node.id === edge.source) && nodes.some(node => node.id === edge.target));
	const limited = edges.slice(0, 200);
	const selected = new Set(limited.flatMap(edge => [edge.source, edge.target]));
	const nodeLines = nodes.filter(node => selected.has(node.id)).slice(0, 400).map(node =>
		`  ${mermaidId(node.id)}["${node.qualifiedName.replace(/["\[\]]/g, "'")}"]`);
	const edgeLines = limited.map(edge => `  ${mermaidId(edge.source)} --> ${mermaidId(edge.target)}`);
	return ['graph LR', ...nodeLines, ...edgeLines].join('\n');
}

function mermaidId(id: string): string {
	return 'n' + createHash('sha256').update(id).digest('hex').slice(0, 16);
}

function reachableCalls(graph: CodeGraph, start: string): string[] {
	const found = new Set<string>();
	const queue = [start];
	while (queue.length && found.size < 200) {
		const current = queue.shift()!;
		for (const edge of graph.edges.filter(item => item.type === 'FUNCTION_CALLS_FUNCTION' && item.source === current && item.resolution !== 'unresolved')) {
			if (!found.has(edge.target)) {
				found.add(edge.target);
				queue.push(edge.target);
			}
		}
	}
	found.delete(start);
	return [...found];
}

function hasCycle(nodes: GraphNode[], edges: CodeGraph['edges']): boolean {
	const adjacency = new Map<string, string[]>();
	for (const edge of edges) {
		adjacency.set(edge.source, [...(adjacency.get(edge.source) ?? []), edge.target]);
	}
	const visiting = new Set<string>();
	const visited = new Set<string>();
	function visit(id: string): boolean {
		if (visiting.has(id)) {return true;}
		if (visited.has(id)) {return false;}
		visiting.add(id);
		for (const next of adjacency.get(id) ?? []) {if (visit(next)) {return true;}}
		visiting.delete(id);
		visited.add(id);
		return false;
	}
	return nodes.some(node => visit(node.id));
}

async function atomicWrite(file: string, contents: string): Promise<void> {
	const temp = `${file}.${process.pid}.tmp`;
	try {
		await fs.writeFile(temp, contents, 'utf8');
		await fs.rename(temp, file);
	} catch (error) {
		await fs.rm(temp, { force: true });
		throw error;
	}
}
